;------------------------------------------------------------------------------
; VOID
; EFIAPI
; AsmClzero (
;   IN  UINT64  Addrs
;   );
;------------------------------------------------------------------------------
AsmClzero   PROC
    mov   rax, rcx
    db    0Fh, 01h, 0FCh    ;opcode of CLZERO
    ret
AsmClzero   ENDP

END

